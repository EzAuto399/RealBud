import { PrivateBackupCatalog, catalogStorageBudget } from "./private-backup-catalog.js";
import { encodePrivateBackupV2, decodePrivateBackupV2 } from "./private-backup-codec.js";
import { PRIVATE_BACKUP_V2_LIMITS } from "../shared/private-backup-v2.js";
import { privateBackupDescriptions } from "./private-workspace-backup.js";
const META = 'realbud:metadata';
const MAX_LOGICAL_ENTRY = 8 * 1024 * 1024;
const decoder = new TextDecoder('utf-8', { fatal: true });
const object = (v) => !!v && typeof v === 'object' && !Array.isArray(v);
function invalid(message = 'The backup archive contains unsupported business data. No restore was prepared.') { throw Object.assign(new Error(message), { status: 400 }); }
function parse(data) { try {
    return JSON.parse(decoder.decode(data));
}
catch {
    return invalid('The backup contains an invalid JSON entry.');
} }
function metadata(value) {
    if (!object(value) || Object.keys(value).sort().join(',') !== 'createdAt,databasePresent,version,workspaceId' || value.version !== 2 ||
        typeof value.workspaceId !== 'string' || !/^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/i.test(value.workspaceId) ||
        typeof value.databasePresent !== 'boolean' || typeof value.createdAt !== 'string' || !Number.isFinite(Date.parse(value.createdAt)) || new Date(value.createdAt).toISOString() !== value.createdAt)
        invalid();
    return value;
}
function receipt(meta, summary, transport) {
    if (!meta.databasePresent && summary.records)
        invalid('The archive declares no workflow history but contains workflow records.');
    return { digest: transport.archiveDigest, createdAt: meta.createdAt, workspaceId: meta.workspaceId,
        fileCount: summary.files + Number(meta.databasePresent), recordCount: summary.records,
        plainBytes: summary.plainBytes, ...privateBackupDescriptions() };
}
function entry(name, bytes) {
    return { name, size: bytes.length, data: (async function* () {
            for (let offset = 0; offset < bytes.length; offset += PRIVATE_BACKUP_V2_LIMITS.frameBytes)
                yield bytes.subarray(offset, offset + PRIVATE_BACKUP_V2_LIMITS.frameBytes);
        })() };
}
/** A source capture must be complete and immutable before its archive can be
 * published. Exact ordinary file bytes and record insertion order are retained.
 * No installation or source encryption key is serialized into the archive. */
export async function* encodeBackupCatalog(catalog, options) {
    const meta = metadata({ version: 2, createdAt: options.createdAt, workspaceId: catalog.workspaceId, databasePresent: options.databasePresent });
    const original = catalog.seal();
    if (!meta.databasePresent && original.records)
        invalid();
    async function* entries() {
        yield entry(META, Buffer.from(JSON.stringify(meta)));
        for (const file of catalog.iterateFiles())
            yield entry(`file:${file.encoding}:${file.path}`, file.data);
        for (const record of catalog.iterateRecords())
            yield entry(`record:${record.id}`, Buffer.from(JSON.stringify(record)));
        // Corruption or an unexpected writer must fail before the footer is emitted.
        const final = catalog.validate();
        if (final.digest !== original.digest || final.entries !== original.entries)
            invalid('The captured backup changed before sealing. No complete archive was produced.');
    }
    yield* encodePrivateBackupV2(entries(), { passphrase: options.passphrase, signal: options.signal, limits: options.limits,
        onComplete: async (transport) => { await options.onComplete?.({ metadata: meta, transport, receipt: receipt(meta, original, transport) }); } });
}
/** The directory is generated by the host and must not exist. A failed decode
 * leaves only a closed, provisional encrypted catalog; its owner retains or
 * explicitly removes it. It is never a trusted preview or a staged restore. */
export async function decodeBackupCatalog(input, options) {
    if (typeof options.expectedArchiveDigest !== 'string' || !/^[a-f0-9]{64}$/.test(options.expectedArchiveDigest))
        invalid('The uploaded backup digest is missing.');
    const catalogLimits = { maxEntries: options.catalogMaxEntries ?? PRIVATE_BACKUP_V2_LIMITS.entryCount - 1, maxBytes: options.catalogMaxBytes ?? PRIVATE_BACKUP_V2_LIMITS.archiveBytes, maxStorageBytes: options.catalogMaxStorageBytes };
    catalogStorageBudget(catalogLimits); // Validate capacity before reading input or creating files.
    let catalog, meta;
    let creating;
    let current;
    try {
        const transport = await decodePrivateBackupV2(input, {
            passphrase: options.passphrase, signal: options.signal, limits: options.limits,
            visitor: {
                begin(value) {
                    if (current || value.index === 0 && value.name !== META || value.index !== 0 && value.name === META)
                        invalid();
                    if (value.name === META ? value.size > 4096 : !value.name.startsWith('file:') && !value.name.startsWith('record:'))
                        invalid();
                    // The record envelope adds bounded identity fields to a logical body.
                    if (value.size > MAX_LOGICAL_ENTRY + 1024)
                        invalid('A backup entry exceeds its business record limit.');
                    current = { name: value.name, bytes: Buffer.alloc(value.size), offset: 0 };
                },
                data(bytes) {
                    if (!current || current.offset + bytes.length > current.bytes.length)
                        invalid();
                    current.bytes.set(bytes, current.offset);
                    current.offset += bytes.length;
                },
                async end(value) {
                    if (!current || value.name !== current.name || current.offset !== current.bytes.length)
                        invalid();
                    const { name, bytes } = current;
                    current = undefined;
                    try {
                        if (name === META) {
                            meta = metadata(parse(bytes));
                            creating = PrivateBackupCatalog.create({ directory: options.directory, key: options.key, workspaceId: meta.workspaceId,
                                ...catalogLimits });
                            catalog = await creating;
                            return;
                        }
                        if (!catalog || !meta)
                            invalid();
                        const file = /^file:(bytes|json):(.+)$/.exec(name);
                        if (file) {
                            catalog.addFile({ path: file[2], encoding: file[1], data: bytes });
                            return;
                        }
                        if (!name.startsWith('record:'))
                            invalid();
                        const row = parse(bytes);
                        if (!object(row) || Object.keys(row).sort().join(',') !== 'id,kind,revision,value' || row.id !== name.slice(7) || typeof row.id !== 'string' || typeof row.kind !== 'string' || !Number.isSafeInteger(row.revision))
                            invalid();
                        catalog.addRecord({ id: row.id, kind: row.kind, revision: Number(row.revision), value: row.value });
                    }
                    finally {
                        bytes.fill(0);
                    }
                },
            },
        });
        if (current || !catalog || !meta || transport.archiveDigest !== options.expectedArchiveDigest)
            invalid('The complete backup differs from the uploaded copy. Preview it again.');
        if (!meta.databasePresent && catalog.countRecords())
            invalid();
        const summary = catalog.seal();
        return { catalog, metadata: meta, transport, receipt: receipt(meta, summary, transport) };
    }
    catch (error) {
        // The codec can abort while an async visitor is still creating its owned
        // catalog. Drain that creation before reporting cancellation to its owner.
        const created = await creating?.catch(() => undefined);
        (catalog ?? created)?.close();
        current?.bytes.fill(0);
        throw error;
    }
}
